"""Pure planning arithmetic and fail-closed grant checks; contains no sender."""
from __future__ import annotations

import json
import hashlib
import math
from pathlib import Path
from datetime import datetime, timezone


def load_budget(lab):
    budget=json.loads((Path(lab) / "configs/pilot-budget-v1.json").read_text(encoding="utf-8"))
    budget["_lab_root"]=str(Path(lab).resolve())
    return budget


def calculate_candidate_budget(budget):
    rates = budget["price_basis"]
    expected_in = budget["expected_tokens_per_candidate"]["input"] / 1_000_000
    expected_out = budget["expected_tokens_per_candidate"]["output"] / 1_000_000
    expected = sum(expected_in * rates[m]["input_per_million"] + expected_out * rates[m]["output_per_million"] for m in rates)
    candidate_count = budget["planned_candidate_replies"]
    retries = budget["candidate_external_calls_max"] - candidate_count
    if retries < 0 or retries > 3:
        raise ValueError("invalid candidate retry envelope")
    worst_in=budget["worst_case_tokens_per_candidate"]["input"]
    worst_out=budget["worst_case_tokens_per_candidate"]["output"]
    cache_write_bound=sum(worst_in*rates[m]["cache_write_input_per_million"] / 1_000_000 +
                          worst_out*rates[m]["output_per_million"] / 1_000_000 for m in rates)
    retry_input=budget["per_request_token_caps"]["input"]
    retry_output=budget["per_request_token_caps"]["output"]
    retry_bound=sum(retry_input*rates[m]["cache_write_input_per_million"] / 1_000_000 +
                    retry_output*rates[m]["output_per_million"] / 1_000_000 for m in rates)
    maximum=(cache_write_bound+retry_bound)*budget["contingency_factor"]
    maximum_ceiling=math.ceil(maximum*1_000_000)/1_000_000
    if maximum_ceiling!=budget["candidate_worst_case_reserve_usd"]:
        raise ValueError("candidate reserve does not match frozen rates, caps and contingency")
    if maximum > budget["candidate_only_stop_threshold_usd"]:
        raise ValueError("candidate reserve exceeds proposed stop threshold")
    return {"expected_candidate_usd": round(expected, 6), "maximum_candidate_usd": maximum_ceiling,
            "candidate_external_calls_max": budget["candidate_external_calls_max"],
            "full_pilot_budget_status": "UNKNOWN_BASELINE" if budget.get("full_pilot_max_usd") is None or budget.get("billing_status") != "VERIFIED" else "ESTIMATED"}


