class BudgetGuard:
    """Authorizes planned request accounting only. This object cannot perform IO."""
    def __init__(self, budget, grant):
        if not isinstance(grant, dict) or not grant.get("owner_approval_id"):
            raise PermissionError("a bound OWNER execution grant is required")
        if grant.get("baseline_billing_verified") is not True or not grant.get("baseline_policy"):
            raise PermissionError("baseline billing/quota policy is unknown")
        if not grant.get("frozen_hashes") or not grant.get("candidate_ids") or not grant.get("expires_at"):
            raise PermissionError("grant must bind exact pilot inputs and expiry")
        try:
            expires=datetime.fromisoformat(grant["expires_at"].replace("Z", "+00:00"))
            if expires.tzinfo is None or expires <= datetime.now(timezone.utc):
                raise ValueError
        except (TypeError, ValueError):
            raise PermissionError("grant expiry must be a future timezone-aware timestamp") from None
        frozen=json.loads((Path(budget["_lab_root"])/"configs/pilot-v1.json").read_text(encoding="utf-8"))
        frozen_sha=hashlib.sha256((Path(budget["_lab_root"])/"configs/pilot-v1.json").read_bytes()).hexdigest()
        ids_sha=hashlib.sha256(json.dumps(frozen["scenario_ids"],ensure_ascii=False,separators=(",", ":")).encode()).hexdigest()
        expected_hashes={"pilot_config_sha256":frozen_sha,"scenario_ids_sha256":ids_sha}
        if grant.get("pilot_id")!=budget.get("pilot_id") or grant.get("candidate_ids")!=budget.get("pilot_id") or grant.get("frozen_hashes")!=expected_hashes:
            raise PermissionError("grant pilot ID and frozen hashes do not match this candidate")
        if budget.get("billing_status") != "VERIFIED" or budget.get("full_pilot_max_usd") is None:
            raise PermissionError("full-pilot maximum remains unknown")
        total_usd=grant.get("total_usd")
        if type(total_usd) not in {int,float} or not math.isfinite(total_usd) or total_usd<budget["full_pilot_max_usd"]:
            raise PermissionError("grant USD ceiling does not cover the verified full-pilot maximum")
        if total_usd < calculate_candidate_budget(budget)["maximum_candidate_usd"]:
            raise PermissionError("grant USD ceiling is below conservative candidate reserve")
        if grant.get("max_calls", 0) < budget["candidate_external_calls_max"]:
            raise PermissionError("grant call cap is insufficient")
        if grant.get("models") != list(("gpt-6.1-sol", "claude-sonnet-5-5", "gemini-3.8-flash")):
            raise PermissionError("grant candidate model list differs from frozen pilot")
        if type(grant.get("max_baseline_calls")) is not int or grant["max_baseline_calls"]<budget["baseline_external_calls_max"]:
            raise PermissionError("grant baseline call cap is insufficient")
        caps=budget["per_request_token_caps"]
        if any(type(grant.get(field)) is not int or not 1<=grant[field]<=caps[name] for field,name in (("max_input_tokens","input"),("max_output_tokens","output"))):
            raise PermissionError("grant per-request token cap is invalid or exceeds frozen maximum")
        if grant.get("retryable_failure_kinds") != ["transport_error"] or type(grant.get("max_retries_per_model")) is not int or not 0<=grant["max_retries_per_model"]<=1:
            raise PermissionError("grant retry policy exceeds the frozen retry rule")
        self.budget, self.grant = budget, grant
        self.requests = []
        self.retry_counts = {m: 0 for m in grant["models"]}
        self.token_usage = {m: {"input": 0, "output": 0} for m in grant["models"]}
        self.spent_usd = 0.0
        self.baseline_calls = 0

    def _estimate(self, model, input_tokens, output_tokens):
        rate = self.budget["price_basis"].get(model)
        if rate is None:
            raise PermissionError("model is not covered by grant")
        # Match the frozen conservative reserve: assume every input token incurs
        # the provider's cache-write rate, even when no cache is actually used.
        return input_tokens * rate["cache_write_input_per_million"] / 1_000_000 + output_tokens * rate["output_per_million"] / 1_000_000

    def authorize_request(self, model, *, input_tokens, output_tokens, retry=False):
        if model not in self.grant["models"]:
            raise PermissionError("model is not covered by grant")
        if type(input_tokens) is not int or type(output_tokens) is not int or input_tokens < 0 or output_tokens < 0:
            raise PermissionError("token estimates must be non-negative integers")
        if input_tokens > min(32768, self.grant["max_input_tokens"]) or output_tokens > min(2048, self.grant["max_output_tokens"]):
            raise PermissionError("request exceeds frozen per-request token cap")
        model_usage = self.token_usage[model]
        totals = self.budget["worst_case_tokens_per_candidate"]
        retry_allowance = self.budget["per_request_token_caps"] if retry else {"input": 0, "output": 0}
        if model_usage["input"] + input_tokens > totals["input"] + retry_allowance["input"] or model_usage["output"] + output_tokens > totals["output"] + retry_allowance["output"]:
            raise PermissionError("cumulative per-model token envelope exhausted")
        if len(self.requests) >= min(self.budget["candidate_external_calls_max"], self.grant["max_calls"]):
            raise PermissionError("request call cap exhausted")
        if retry:
            if self.retry_counts[model] >= min(1, self.grant["max_retries_per_model"]):
                raise PermissionError("retry cap exhausted")
        charge = self._estimate(model, input_tokens, output_tokens) * self.budget["contingency_factor"]
        if self.spent_usd + charge > min(self.grant["total_usd"], self.budget["candidate_only_stop_threshold_usd"]):
            raise PermissionError("conservative USD allowance exhausted")
        self.spent_usd += charge
        model_usage["input"] += input_tokens
        model_usage["output"] += output_tokens
        if retry:
            self.retry_counts[model] += 1
        self.requests.append({"model": model, "input_tokens": input_tokens, "output_tokens": output_tokens, "retry": retry, "estimate_usd": charge})

    def retry_allowed(self, model, failure_kind):
        return model in self.retry_counts and failure_kind in self.grant["retryable_failure_kinds"] and self.retry_counts[model] < self.grant["max_retries_per_model"]

    def authorize_baseline_call(self):
        if not self.grant.get("baseline_billing_verified") or not self.grant.get("baseline_policy"):
            raise PermissionError("baseline subscription quota has not been verified")
        if self.baseline_calls >= min(self.budget["baseline_external_calls_max"], self.grant["max_baseline_calls"]):
            raise PermissionError("baseline call cap exhausted")
        self.baseline_calls += 1

    def snapshot(self):
        return {"candidate_calls": len(self.requests), "baseline_calls": self.baseline_calls,
                "candidate_tokens_by_model": self.token_usage,
                "estimated_candidate_usd": round(self.spent_usd, 8), "requests": list(self.requests)}
