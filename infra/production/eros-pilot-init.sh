#!/bin/sh
set -eu
export PGPASSWORD="$POSTGRES_PASSWORD"
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv eros_migrator_password EROS_PILOT_MIGRATOR_PASSWORD
\getenv eros_runtime_password EROS_PILOT_RUNTIME_PASSWORD
CREATE ROLE eros_ddl NOLOGIN NOSUPERUSER NOCREATEDB NOBYPASSRLS;
CREATE ROLE eros_migrator LOGIN PASSWORD :'eros_migrator_password' NOSUPERUSER NOCREATEDB NOBYPASSRLS;
CREATE ROLE eros_runtime LOGIN PASSWORD :'eros_runtime_password' NOSUPERUSER NOCREATEDB BYPASSRLS;
REVOKE CONNECT ON DATABASE eros_pilot FROM PUBLIC;
GRANT CONNECT, CREATE ON DATABASE eros_pilot TO eros_migrator;
GRANT CONNECT ON DATABASE eros_pilot TO eros_runtime;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
CREATE SCHEMA engine AUTHORIZATION eros_ddl;
GRANT USAGE, CREATE ON SCHEMA public TO eros_migrator;
GRANT USAGE, CREATE ON SCHEMA engine TO eros_migrator;
GRANT USAGE ON SCHEMA public, engine TO eros_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE eros_migrator IN SCHEMA engine
  GRANT ALL ON TABLES TO eros_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE eros_migrator IN SCHEMA engine
  GRANT ALL ON SEQUENCES TO eros_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE eros_migrator IN SCHEMA engine
  GRANT EXECUTE ON FUNCTIONS TO eros_runtime;
SQL
