import { test, expect } from '@playwright/test';
import { apiRead, choosePng, creatorPage, moderationActions, tinyMp4, waitForApi } from './helpers';

test('post and reel rejection, resubmission and approval are real UI transitions', async ({ page, browser }) => {
  await creatorPage(page, 'content-rejection');
  const creator = (await apiRead<any>(page, '/creator/me')).creator;
  const adminContext = await browser.newContext({ baseURL: process.env.GPOINT_MINIAPP_URL ?? 'http://127.0.0.1:5177' });
  const admin = await adminContext.newPage();
  await admin.goto('/admin');
  await expect(admin.getByRole('heading', { name: 'Moderation' })).toBeVisible();

  await page.getByRole('button', { name: 'Content', exact: true }).click();
  const postCaption = `E2E rejected post ${Date.now()}`;
  await page.getByLabel('Post caption').fill(postCaption);
  await choosePng(page, 0);
  await waitForApi(page, '/creator/me/posts', () => page.getByRole('button', { name: 'Save Draft', exact: true }).click());
  const post = (await apiRead<any>(page, '/creator/me/posts')).items.find((x: any) => x.caption === postCaption);
  expect(post?.id).toBeTruthy();
  const postItems = (await apiRead<any>(page, '/creator/me/posts')).items;
  const postIndex = postItems.findIndex((x: any) => x.id === post.id);
  const postSubmitIndex = postItems.slice(0, postIndex).filter((x: any) => x.status === 'DRAFT').length;
  const postSubmit = page.getByRole('button', { name: 'Submit for Moderation', exact: true }).nth(postSubmitIndex);
  await waitForApi(page, `/creator/me/posts/${post.id}`, () => postSubmit.click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/posts')).items.find((x: any) => x.id === post.id)?.status).toBe('PENDING');
  await admin.reload();
  await admin.getByRole('button', { name: 'Content', exact: true }).click();
  const postRow = admin.getByRole('article').filter({ hasText: postCaption });
  await expect(postRow.locator(`img[data-media-id="${post.media[0].mediaAssetId}"]`)).toHaveJSProperty('naturalWidth', 1);
  await admin.getByLabel('Moderation reason').fill('Post E2E rejection');
  await waitForApi(admin, `/admin/posts/${post.id}/REJECT`, () => postRow.getByRole('button', { name: 'Reject', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/posts')).items.find((x: any) => x.id === post.id)?.moderationReason).toBe('Post E2E rejection');
  await page.reload();
  await page.getByRole('button', { name: 'Content', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit & Resubmit', exact: true }).last()).toBeVisible();
  await page.getByLabel('Post caption').fill(`${postCaption} edited`);
  await page.getByRole('button', { name: 'Edit & Resubmit', exact: true }).last().click();
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/posts')).items.find((x: any) => x.id === post.id)?.status).toBe('PENDING');
  await admin.reload();
  await admin.getByRole('button', { name: 'Content', exact: true }).click();
  const postRow2 = admin.getByRole('article').filter({ hasText: postCaption });
  await waitForApi(admin, `/admin/posts/${post.id}/APPROVE`, () => postRow2.getByRole('button', { name: 'Approve', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/posts')).items.find((x: any) => x.id === post.id)?.status).toBe('PUBLISHED');
  const postHistory = await moderationActions('POST', post.id);
  expect(postHistory.map(x => x.action)).toEqual(expect.arrayContaining(['REJECT', 'APPROVE']));

  await page.getByRole('button', { name: 'Reels', exact: true }).click();
  const reelCaption = `E2E rejected reel ${Date.now()}`;
  await page.locator('input[type=file]').nth(1).setInputFiles({ name: 'e2e-rejected.mp4', mimeType: 'video/mp4', buffer: tinyMp4 });
  await page.getByLabel('Reel caption').fill(reelCaption);
  await waitForApi(page, '/creator/me/reels', () => page.getByRole('button', { name: 'Save Draft', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/reels')).items.find((x: any) => x.caption === reelCaption)).toBeTruthy();
  const reel = (await apiRead<any>(page, '/creator/me/reels')).items.find((x: any) => x.caption === reelCaption);
  expect(reel?.id).toBeTruthy();
  await page.getByRole('button', { name: 'Submit for Moderation', exact: true }).last().click();
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/reels')).items.find((x: any) => x.id === reel.id)?.status).toBe('PENDING');
  await admin.reload();
  await admin.getByRole('button', { name: 'Content', exact: true }).click();
  const reelRow = admin.getByRole('article').filter({ hasText: reelCaption });
  const reelMedia = await admin.evaluate(async (id) => { const token = localStorage.getItem('gpoint.session'); const r = await fetch(`${location.origin.replace(':5177', ':3022')}/media/assets/${id}`, { headers: { authorization: `Bearer ${token}` } }); return { ok: r.ok, type: r.headers.get('content-type'), size: (await r.arrayBuffer()).byteLength }; }, reel.media[0].mediaAssetId);
  expect(reelMedia.ok).toBeTruthy();
  expect(reelMedia.type).toBe('video/mp4');
  expect(reelMedia.size).toBeGreaterThan(0);
  await admin.getByLabel('Moderation reason').fill('Reel E2E rejection');
  await waitForApi(admin, `/admin/posts/${reel.id}/REJECT`, () => reelRow.getByRole('button', { name: 'Reject', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/reels')).items.find((x: any) => x.id === reel.id)?.moderationReason).toBe('Reel E2E rejection');
  await page.reload();
  await page.getByRole('button', { name: 'Content', exact: true }).click();
  await page.getByRole('button', { name: 'Reels', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit & Resubmit', exact: true }).last()).toBeVisible();
  await page.getByRole('button', { name: 'Edit & Resubmit', exact: true }).last().click();
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/reels')).items.find((x: any) => x.id === reel.id)?.status).toBe('PENDING');
  await admin.reload();
  await admin.getByRole('button', { name: 'Content', exact: true }).click();
  await waitForApi(admin, `/admin/posts/${reel.id}/APPROVE`, () => admin.getByRole('article').filter({ hasText: reelCaption }).getByRole('button', { name: 'Approve', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/reels')).items.find((x: any) => x.id === reel.id)?.status).toBe('PUBLISHED');
  const reelHistory = await moderationActions('POST', reel.id);
  expect(reelHistory.map(x => x.action)).toEqual(expect.arrayContaining(['REJECT', 'APPROVE']));
  await adminContext.close();
});
