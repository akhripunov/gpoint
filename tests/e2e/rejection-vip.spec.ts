import { test, expect } from '@playwright/test';
import { apiRead, creatorPage, moderationActions, waitForApi } from './helpers';

test('VIP rejection, resubmission and approval are real UI transitions', async ({ page, browser }) => {
  await creatorPage(page, 'vip-rejection');
  const creator = (await apiRead<any>(page, '/creator/me')).creator;
  const adminContext = await browser.newContext({ baseURL: process.env.GPOINT_MINIAPP_URL ?? 'http://127.0.0.1:5177' });
  const admin = await adminContext.newPage();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await waitForApi(page, '/creator/me/submit', () => page.getByRole('button', { name: 'Submit for Moderation', exact: true }).click());
  await admin.goto('/admin');
  const creatorRow = admin.getByRole('article').filter({ hasText: creator.displayName });
  await expect(creatorRow).toContainText('PENDING');
  await waitForApi(admin, `/admin/creators/${creator.id}/APPROVE`, () => creatorRow.getByRole('button', { name: 'Approve', exact: true }).click());
  await page.getByRole('button', { name: 'VIP', exact: true }).click();
  await page.getByLabel('VIP title').fill('E2E Rejected VIP');
  await page.getByLabel('Affiliate URL').fill('https://t.me/e2e_bot?startapp=vip-one');
  await waitForApi(page, '/creator/me/vip', () => page.getByRole('button', { name: 'Save / Submit', exact: true }).click());
  const offer = (await apiRead<any>(page, '/creator/me/vip'));
  expect(offer?.id).toBeTruthy();
  expect(offer.status).toBe('PENDING_REVIEW');
  await admin.goto('/admin');
  await admin.getByRole('button', { name: 'VIP', exact: true }).click();
  const row = admin.getByRole('article').filter({ hasText: `${creator.displayName} · E2E Rejected VIP` });
  await expect(row).toContainText('PENDING_REVIEW');
  await admin.getByLabel('Moderation reason').fill('VIP E2E rejection');
  await waitForApi(admin, `/admin/vip/${offer.id}/REJECT`, () => row.getByRole('button', { name: 'Reject', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/vip')).moderationReason).toBe('VIP E2E rejection');
  await page.reload();
  await page.getByRole('button', { name: 'VIP', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save / Submit', exact: true })).toBeVisible();
  await page.getByLabel('VIP title').fill('E2E Rejected VIP');
  await page.getByLabel('Affiliate URL').fill('https://t.me/e2e_bot?startapp=vip-two');
  await waitForApi(page, '/creator/me/vip', () => page.getByRole('button', { name: 'Save / Submit', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/vip')).status).toBe('PENDING_REVIEW');
  await admin.reload();
  await admin.getByRole('button', { name: 'VIP', exact: true }).click();
  const resubmitted = admin.getByRole('article').filter({ hasText: `${creator.displayName} · E2E Rejected VIP` });
  await waitForApi(admin, `/admin/vip/${offer.id}/APPROVE`, () => resubmitted.getByRole('button', { name: 'Approve', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me/vip')).status).toBe('ACTIVE');
  const history = await moderationActions('VIP_OFFER', offer.id);
  expect(history.map(x => x.action)).toEqual(expect.arrayContaining(['REJECT', 'APPROVE']));
  const consumer = await page.context().newPage();
  await consumer.goto('/');
  const card = consumer.getByRole('button', { name: new RegExp(creator.displayName) });
  await expect(card).toBeVisible();
  await card.click();
  await expect(consumer.getByRole('button', { name: 'GET VIP ↗' })).toBeVisible();
  await adminContext.close();
});
