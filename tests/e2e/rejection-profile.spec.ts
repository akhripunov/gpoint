import { test, expect } from '@playwright/test';
import { apiRead, creatorPage, moderationActions, waitForApi } from './helpers';

test('profile rejection, resubmission and approval are real UI transitions', async ({ page, browser }) => {
  await creatorPage(page, 'profile-rejection');
  const creatorBefore = await apiRead<any>(page, '/creator/me');
  const creatorId = creatorBefore.creator.id;
  const displayName = creatorBefore.creator.displayName;
  await page.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByLabel('Bio').fill('Profile rejection edited bio');
  await waitForApi(page, '/creator/me/profile', () => page.getByRole('button', { name: 'Save Draft', exact: true }).click());
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await waitForApi(page, '/creator/me/submit', () => page.getByRole('button', { name: 'Submit for Moderation', exact: true }).click());
  expect((await apiRead<any>(page, '/creator/me')).creator.status).toBe('PENDING');
  const adminContext = await browser.newContext({ baseURL: process.env.GPOINT_MINIAPP_URL ?? 'http://127.0.0.1:5177' });
  const admin = await adminContext.newPage();
  await admin.goto('/admin');
  const creatorRow = admin.getByRole('article').filter({ hasText: displayName });
  await expect(creatorRow).toContainText('PENDING');
  await admin.getByLabel('Moderation reason').fill('Profile E2E rejection');
  await waitForApi(admin, `/admin/creators/${creatorId}/REJECT`, () => creatorRow.getByRole('button', { name: 'Reject', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me')).creator.status).toBe('REJECTED');
  await page.reload();
  await expect(page.getByText('Profile E2E rejection', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByLabel('Bio').fill('Profile rejection resubmitted bio');
  await waitForApi(page, '/creator/me/profile', () => page.getByRole('button', { name: 'Save Draft', exact: true }).click());
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await waitForApi(page, '/creator/me/submit', () => page.getByRole('button', { name: 'Resubmit', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me')).creator.status).toBe('PENDING');
  await admin.reload();
  const resubmittedRow = admin.getByRole('article').filter({ hasText: displayName });
  await expect(resubmittedRow).toContainText('PENDING');
  await waitForApi(admin, `/admin/creators/${creatorId}/APPROVE`, () => resubmittedRow.getByRole('button', { name: 'Approve', exact: true }).click());
  await expect.poll(async () => (await apiRead<any>(page, '/creator/me')).creator.status).toBe('APPROVED');
  const history = await moderationActions('CREATOR', creatorId);
  expect(history.map(x => x.action)).toEqual(expect.arrayContaining(['REJECT', 'APPROVE']));
  const consumer = await page.context().newPage();
  await consumer.goto('/');
  const card = consumer.getByRole('button', { name: new RegExp(displayName) });
  await expect(card).toBeVisible();
  await card.click();
  await expect(consumer.getByRole('heading', { name: displayName })).toBeVisible();
  await adminContext.close();
});
